function stringifyQ(q) {
    return `      {
        "text": "${q.text}",
        "choices": ${JSON.stringify(q.choices, null, 10).replace(/\\n\\s+/g, ' ')},
        "answer": ${JSON.stringify(q.answer)},
        "explain": ${JSON.stringify(q.explain)},
        "wordBank": "",
        "memo": "",
        "slots": [],
        "refId": "",
        "isBonus": false
      }`;
}

const questionsString = newQuestions.map(stringifyQ).join(',\n');

const lines = content.split('\n');

let minpoSoronIndex = -1;
let openBrackets = 0;
let insideSoron = false;

for (let i = 0; i < lines.length; i++) {
    if (lines[i].includes('"民法総論": [')) {
        insideSoron = true;
        openBrackets = 1;
        continue;
    }
    if (insideSoron) {
        if (lines[i].includes('[')) openBrackets++;
        if (lines[i].includes(']')) openBrackets--;

        if (openBrackets === 0) {
            minpoSoronIndex = i;
            break;
        }
    }
}

if (minpoSoronIndex !== -1) {
    if (lines[minpoSoronIndex - 1].trim() === '}') {
        lines[minpoSoronIndex - 1] = lines[minpoSoronIndex - 1] + ',';
    }
    lines.splice(minpoSoronIndex, 0, questionsString);
    const newContent = lines.join('\n');
    fs.writeFileSync('./src/questions.js', newContent, 'utf8');
    console.log("Successfully appended 5 more questions (46-50) to src/questions.js");
} else {
    console.error("Could not find 民法総論 end bracket");
}
