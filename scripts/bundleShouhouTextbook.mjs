function stripExplain(raw) {
  if (!raw) return '';
  return raw
    .replace(/\u200b/g, '')
    .replace(/\[\[red:([\s\S]+?)\]\]/g, '$1')
    .replace(/\*\*/g, '')
    .replace(/\n+/g, ' ')
    .trim()
    .slice(0, 320);
}

function pickChoiceIndex(q) {
  const answers = new Set(q.answer ?? []);
  const text = q.text ?? '';
  const findWrong =
    text.includes('誤っ') ||
    text.includes('誤り') ||
    text.includes('妥当でない') ||
    text.includes('妥当なものでない');
  if (findWrong) {
    const wrong = q.choices.findIndex((_, i) => !answers.has(i));
    if (wrong >= 0) return wrong;
  }
  if (answers.size > 0) return [...answers][0];
  return 0;
}

function questionToQuiz(q, index) {
  const n = index + 1;
  const ci = pickChoiceIndex(q);
  const answers = new Set(q.answer ?? []);
  const statement = (q.choices[ci] ?? '').trim();
  if (!statement) return null;

  const deep = q.choiceDeepDive?.[ci];
  const explain =
    stripExplain(deep) ||
    stripExplain(q.memo) ||
    stripExplain(q.explain) ||
    (answers.has(ci) ? '本肢は正しい。' : '本肢は誤り。');

  return {
    id: `past-${n}`,
    label: `過去問 ${n}`,
    statement,
    correct: answers.has(ci),
    explain,
    chapterId: CHAPTER_BY_Q[n] ?? 'intro',
  };
}

function main() {
  const byChapter = {};
  questions.forEach((q, i) => {
    const quiz = questionToQuiz(q, i);
    if (!quiz) return;
    const { chapterId, ...rest } = quiz;
    if (!byChapter[chapterId]) byChapter[chapterId] = [];
    byChapter[chapterId].push(rest);
  });

  const ts =
    '// Auto-generated by scripts/bundleShouhouTextbook.mjs\n' +
    '// Regenerate: npm run bundle:shouhou-textbook\n\n' +
    "import type { TextbookQuiz } from './shouhouTextbookContent';\n\n" +
    `export const SHOUHOU_PAST_QUIZZES: Record<string, TextbookQuiz[]> = ${JSON.stringify(byChapter, null, 2)};\n`;

  fs.writeFileSync(OUT, ts, 'utf8');
  const total = Object.values(byChapter).reduce((s, a) => s + a.length, 0);
  console.log(`bundleShouhouTextbook: ${questions.length} questions → ${total} quizzes → ${OUT}`);
}

main();
