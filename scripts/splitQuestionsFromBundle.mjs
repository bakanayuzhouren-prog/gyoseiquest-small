/**
 * 既存の src/questions.js（単一バンドル）から科目別 JSON・メタ・ローダーを生成する。
 * syncQuiz 実行ができない環境でも一度だけ実行してマイグレーションできる。
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const src = join(root, 'src');
const questionsPath = join(src, 'questions.js');
const subjectsDir = join(src, 'questions', 'subjects');

const SUBJECT_ORDER = [
  '基礎法学',
  '憲法',
  '行政法',
  '民法',
  '商法・会社法',
  '基礎知識',
  '多肢選択',
  '記述',
];

function escapeSingleQuoted(s) {
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

async function main() {
  if (!existsSync(questionsPath)) {
    console.error('Missing', questionsPath);
    process.exit(1);
  }

  const mod = await import(pathToFileURL(questionsPath).href);
  const SUBJECTS = mod.SUBJECTS;
  const RESOURCES = mod.RESOURCES;
  const STATUTES = mod.STATUTES;

  if (!SUBJECTS || typeof SUBJECTS !== 'object') {
    console.error('SUBJECTS missing');
    process.exit(1);
  }

  mkdirSync(subjectsDir, { recursive: true });

  const keys = Object.keys(SUBJECTS);
  const iterationOrder = [
    ...SUBJECT_ORDER.filter((k) => keys.includes(k)),
    ...keys.filter((k) => !SUBJECT_ORDER.includes(k)),
  ];

  for (const subj of keys) {
    const inner = SUBJECTS[subj];
    const filePath = join(subjectsDir, `${subj}.json`);
    writeFileSync(filePath, JSON.stringify(inner, null, 2) + '\n', 'utf8');
    console.log('wrote', filePath);
  }

  const manifest = {};
  for (const k of keys) {
    manifest[k] = Object.keys(SUBJECTS[k] || {});
  }

  const manifestPath = join(src, 'questionsManifest.json');
  writeFileSync(
    manifestPath,
    JSON.stringify({ subjectIterationOrder: iterationOrder, subjectManifest: manifest }, null, 2) + '\n',
    'utf8'
  );
  console.log('wrote', manifestPath);

  const metaPath = join(src, 'questionsMeta.js');
  const metaBody =
    '// Generated by splitQuestionsFromBundle.mjs / syncQuiz.js\n' +
    `export const RESOURCES = ${JSON.stringify(RESOURCES, null, 2)};\n` +
    `export const STATUTES = ${JSON.stringify(STATUTES, null, 2)};\n`;
  writeFileSync(metaPath, metaBody, 'utf8');
  console.log('wrote', metaPath);

  const loadersPath = join(src, 'subjectLoaders.ts');
  const loaderLines = keys
    .sort()
    .map((k) => `  '${escapeSingleQuoted(k)}': () => import('./questions/subjects/${escapeSingleQuoted(k)}.json'),`)
    .join('\n');

  const loadersBody =
    `// Generated — do not edit by hand (syncQuiz.js / splitQuestionsFromBundle.mjs)\n` +
    `import type { SubjectCategoryMap } from './subjectData';\n\n` +
    `export const subjectLoaders: Record<string, () => Promise<{ default: SubjectCategoryMap }>> = {\n${loaderLines}\n};\n`;
  writeFileSync(loadersPath, loadersBody, 'utf8');
  console.log('wrote', loadersPath);

  console.log('Done. You may remove or keep src/questions.js; app should use src/questions.ts + chunks.');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
