/**
 * 商法・会社法ぷらす：模試 packed 論点を 1カード1論点へ分割する。
 * emitBonus: false の兄弟トピックを JSON に挿入（ボーナス問題は増やさない）。
 */
import fs from 'node:fs';

function extra(parent, patch) {
  return {
    questionNumber: parent.questionNumber,
    subject: parent.subject,
    field: parent.field,
    learnSubject: parent.learnSubject || '商法・会社法',
    quizSubject: parent.quizSubject || '商法・会社法',
    quizField: parent.quizField || '商法・会社法',
    emitBonus: false,
    sourceTrace: parent.sourceTrace,
    status: 'confirmed',
    ...patch,
  };
}

function applyFile(file, ops) {
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  const byId = new Map(data.topics.map((t) => [t.id, t]));
  let added = 0;
  for (const op of ops) {
    const parent = byId.get(op.after);
    if (!parent) throw new Error(`${file}: missing ${op.after}`);
    if (op.update) Object.assign(parent, op.update);
    const extras = (op.extras || []).map((p) => extra(parent, p));
    const insertAt = data.topics.findIndex((t) => t.id === op.after) + 1;
    const fresh = extras.filter((e) => !byId.has(e.id));
    if (fresh.length) {
      data.topics.splice(insertAt, 0, ...fresh);
      for (const e of fresh) byId.set(e.id, e);
      added += fresh.length;
    }
  }
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n');
  return added;
}

