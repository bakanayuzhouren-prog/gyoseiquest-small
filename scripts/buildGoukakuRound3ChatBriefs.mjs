function uniq(arr) {
  return [...new Set(arr.filter(Boolean))];
}

function buildTriggers(t, extra) {
  const base = [
    t.topic,
    ...(t.references || [])
      .map((r) => String(r))
      // 条文番号・一般すぎる語はトリガーにしない（誤ヒット防止）
      .filter((r) => r.length >= 3 && r.length <= 18 && !/^(取消訴訟|憲法|民法|行政法|会社法|刑法)$/.test(r)),
    `合格革命 問${t.questionNumber}`,
    `第3回 問${t.questionNumber}`,
    `${t.topic}ってなに`,
    `${t.topic}とは`,
    `${t.topic} 違い`,
    `${t.topic} わからん`,
  ];
  return uniq([...(extra?.triggers || []), ...base]).slice(0, 28);
}

function buildText(t, extra) {
  const qs = [
    [`${t.topic}ってなに？`, t.rule],
    ['試験の芯は？', t.aim],
    ['ひっかけは？', t.trap],
    ['暗記フレーズは？', t.memory],
    ...(extra?.extraQs || []),
  ];

  const lines = [
    `## 合格革命第3回・問${t.questionNumber}：${t.topic}`,
    '',
    '**結論（先に答え）**',
    t.rule,
    '',
    '---',
    '',
    '### 多角Q（同じ論点を別角度で）',
    '',
  ];

  qs.forEach(([q, a], i) => {
    lines.push(`**Q${i + 1}. ${q}**`);
    lines.push(`A. ${a}`);
    lines.push('');
  });

  lines.push('---', '');
  lines.push('**ひっかけ**');
  lines.push(t.trap);
  lines.push('');
  lines.push('**もっと噛み砕く**');
  lines.push(t.deepDive);
  lines.push('');
  lines.push('**暗記**');
  lines.push(t.memory);
  lines.push('');
  lines.push(`**出典メモ** 合格革命直前予想模試 第3回・問${t.questionNumber}（${t.learnSubject}）`);

  return lines.join('\n');
}

