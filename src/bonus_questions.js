/** @param {Record<string, Record<string, unknown[]>>} base @param {Record<string, Record<string, unknown[]>>} extra */
function mergeBonusQuestions(base, extra) {
  const out = { ...base };
  for (const [subject, fields] of Object.entries(extra)) {
    if (!out[subject]) out[subject] = {};
    else out[subject] = { ...out[subject] };
    for (const [field, questions] of Object.entries(fields)) {
      const prev = out[subject][field];
      out[subject][field] = [...(Array.isArray(prev) ? prev : []), ...questions];
    }
  }
  return out;
}

