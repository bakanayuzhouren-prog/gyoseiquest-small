function buildTac3ShortDeepdive(subject, card) {
  const cleanText = String(card.text || '')
    .replace(/^【TAC3問([0-9]+)】/, '問$1:')
    .trim();
  const focus = buildTacDeepdiveFocus(subject, cleanText);
  return [
    `まず覚えるのはここ。${cleanText}`,
    focus,
    '過去問では、正しいキーワードをそのまま聞くより、主語・時期・例外・効果を一つだけずらしてきます。カードを聞いたあと、「逆にこれはダメ」という肢を一つ口に出せると点に変わります。',
    '身近にいうと、制度名を覚えるより、入口の条件、動ける人、最後に起きる効果を順番に確認する感じです。',
  ].join('\n\n');
}

for (const [subject, cards] of Object.entries(TAC3_ALL_QUESTION_SHORT_CARDS)) {
  if (!TAC_LEARN_BY_SUBJECT[subject]) TAC_LEARN_BY_SUBJECT[subject] = [];
  const enrichedCards = cards.map((card) => ({
    ...card,
    deepdive: card.deepdive || buildTac3ShortDeepdive(subject, card),
  }));
  TAC_LEARN_BY_SUBJECT[subject].unshift(...enrichedCards);
}

