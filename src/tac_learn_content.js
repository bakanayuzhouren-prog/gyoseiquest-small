function polishTacDeepdiveText(text) {
  return String(text || '')
    .replace(/\r\n/g, '\n')
    .replace(/```(?:text)?\n?/g, '')
    .replace(/```/g, '')
    .replace(/^#{1,6}\s*/gm, '')
    .replace(/^[-*]\s+/gm, '・')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

