function makeDeepDive(law, statute, explain, trap, choice, correct) {
  return [
    `1. この肢の結論`,
    `${correct ? '○ 条文の整理に合う肢です。' : '× 条文の要件・主体・時期を取り違えた肢です。'} ${choice}`,
    '',
    `2. ${law}の条文軸`,
    `${statute}。${explain}`,
    '',
    '3. ひっかけポイント',
    trap,
    '',
    '4. 本番の見分け方',
    '「誰が」「いつまでに」「何をできる・しなければならないか」を分け、「常に・一切・無条件」という強い語を疑います。',
  ].join('\n');
}

function makeQuestion([law, text, choices, answer, statute, explain, trap, source = '現行条文']) {
  return {
    text: `【条文ボーナス】${text}`,
    choices,
    answer: [answer],
    explain,
    choiceExplanations: choices.map((choice, index) =>
      index === answer ? `正解肢。${explain}` : `誤答肢。「${choice}」は、${trap}`,
    ),
    choiceDeepDive: choices.map((choice, index) =>
      makeDeepDive(law, statute, explain, trap, choice, index === answer),
    ),
    isBonus: true,
    wordBank: '',
    memo: `${source}を論点化したオリジナル問題。問題文・選択肢の転載なし。根拠: ${statute}`,
    slots: [],
  };
}

