function tacSourceOf(question) {
  const sourceText = `${question?.memo || ''} ${question?.text || ''}`;
  if (sourceText.includes('TAC第3回') || sourceText.includes('TAC3')) return 'TAC第3回';
  if (sourceText.includes('TAC第2回') || sourceText.includes('TAC2')) return 'TAC第2回';
  return 'TAC第1回';
}

function buildTacChoiceDeepDive(question, subject, field, choiceIndex) {
  const choiceText = String(question?.choices?.[choiceIndex] || '');
  const correctIndexes = Array.isArray(question?.answer) ? question.answer : [];
  const isCorrect = correctIndexes.includes(choiceIndex);
  const source = tacSourceOf(question);
  const correctLabels = correctIndexes.map((index) => `${index + 1}`).join('・') || '未設定';

  return [
    `# ${source} ${subject} / ${field} のもっと深掘る`,
    '',
    '## この肢の位置づけ',
    `- この肢は **${isCorrect ? '正解側' : '誤答側'}** の確認肢です。`,
    `- 正解番号: ${correctLabels}`,
    `- 肢: ${choiceText}`,
    '',
    '## コア解説',
    question?.explain || 'この問題は、結論だけでなく、主語・要件・効果・例外のずれを見抜く練習です。',
    '',
    '## 図解',
    '```text',
    '問題文',
    '  ↓ 主語を確認',
    `${subject} / ${field}`,
    '  ↓ 要件・例外・時期を分ける',
    isCorrect ? 'この肢は要件に合う' : 'この肢はどこかの語句が崩れる',
    '  ↓',
    isCorrect ? '正解肢として採用' : '誤答肢として除外',
    '```',
    '',
    '## 30秒チェック',
    '- この肢の主語は誰か。',
    '- 条文・判例の要件はどの言葉か。',
    '- 「常に」「一切」「必ず」「できる」の語尾が強すぎないか。',
    '- 正解肢と逆にした場合、どの語句を直せば妥当になるか。',
    '',
    '## 君の教科書メモ',
    `この論点は ${source} 由来の自作ボーナス問題として、原文転載ではなく論点を抽出して再構成しています。`,
  ].join('\n');
}

function enrichTacBonusQuestions(base) {
  const out = {};
  for (const [subject, fields] of Object.entries(base)) {
    out[subject] = {};
    for (const [field, questions] of Object.entries(fields)) {
      out[subject][field] = questions.map((question) => {
        const choices = Array.isArray(question.choices) ? question.choices : [];
        const choiceDeepDive = choices.map((_, index) => buildTacChoiceDeepDive(question, subject, field, index));
        const choiceExplanations = choices.map((_, index) => {
          const correctIndexes = Array.isArray(question.answer) ? question.answer : [];
          const isCorrect = correctIndexes.includes(index);
          return isCorrect
            ? `正解肢。${question.explain || '要件と効果が問題文に合っています。'}`
            : `誤答肢。${question.explain || '要件・例外・時期・主体のどこがずれているかを確認します。'}`;
        });
        return {
          ...question,
          choiceDeepDive: question.choiceDeepDive || choiceDeepDive,
          choiceExplanations: question.choiceExplanations || choiceExplanations,
        };
      });
    }
  }
  return out;
}

