/**
 * 民法・常識で切るボーナス。自作。過去問原文なし。
 */

function markBonus(question) {
  const choices = Array.isArray(question.choices) ? question.choices : [];
  const answer = Array.isArray(question.answer) ? question.answer : [];
  return {
    ...question,
    isBonus: true,
    wordBank: question.wordBank || '',
    slots: question.slots || [],
    choiceDeepDive:
      question.choiceDeepDive ||
      choices.map((text, index) =>
        [
          '# 常識で切る のもっと深掘る',
          '',
          `この肢は **${answer.includes(index) ? '正解側' : '誤答側'}**。`,
          '',
          question.explain || '',
          '',
          `- 肢: ${text}`,
        ].join('\n')
      ),
    choiceExplanations:
      question.choiceExplanations ||
      choices.map((_, index) =>
        answer.includes(index) ? `正解肢。${question.explain || ''}` : '誤答肢。制度の○×を取り違えている。'
      ),
  };
}

