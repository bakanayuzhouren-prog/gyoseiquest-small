export function kisoHougakuChoiceExplain(
  subject: string | undefined,
  questionText: string,
  choiceIndex: number,
): string {
  if (subject !== '基礎法学') return '';
  const text = questionText || '';
  for (const pack of PACKS) {
    if (!pack.test(text)) continue;
    return pack.lines[choiceIndex] || '';
  }
  return '';
}
