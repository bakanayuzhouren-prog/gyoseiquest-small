export function buildRelevantConstitutionDeepDive(input: Input): string {
  if (SAFE_EXISTING_GUIDE_STEM.test(input.stem)) {
    return buildConstitutionQuizDeepDive(input);
  }

  const guide = AXES.find((item) => item.test.test(input.stem));
  const verdict = input.legallyCorrect == null
    ? 'この問題は、選択肢全体の組合せまたは順序で判定します。'
    : input.legallyCorrect
      ? 'この肢は、判例・条文の整理に沿っています。'
      : 'この肢は、判例・条文の整理と一致しません。';
  const title = guide?.title || 'この問題の憲法上の整理';
  const axis = guide?.axis || '問題文が示す権利・制度を特定し、保障範囲、制約目的、手段との関連性、判断権者の裁量、判例の射程の順に確認します。';
  const trap = guide?.trap || '「常に」「一切」「直ちに」などの断定が、判例の例外や比較衡量を消していないか確認します。';
  const choice = input.choice.replace(/\s+/g, ' ').slice(0, 90);

  return [
    `${title}\nこの問題で使う判断枠組みを整理します。`,
    `1. この肢の判定\n${verdict}`,
    `2. 判断の軸\n${axis}`,
    `3. この肢の確認ポイント\n「${choice}${input.choice.length > 90 ? '…' : ''}」のうち、判断の軸と一致する部分、言い過ぎている部分、主体を入れ替えた部分を確認します。`,
    `4. 本番の見分け方\n${trap}`,
  ].join('\n\n');
}
