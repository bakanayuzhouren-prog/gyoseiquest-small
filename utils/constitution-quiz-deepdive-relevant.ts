import { buildConstitutionQuizDeepDive } from '@/utils/constitution-quiz-deepdive';

type Input = {
  stem: string;
  choice: string;
  legallyCorrect: boolean | null;
};

const SAFE_EXISTING_GUIDE_STEM =
  /外国人の人権|百里基地|自衛隊基地|予防接種|住基ネット|捜査とプライバシー|夫婦同氏制|法の下の平等|信教の自由|神社の敷地|教科書検定|ため池の堤とう|適正手続|第三者没収|生存権|司法権の限界/;

