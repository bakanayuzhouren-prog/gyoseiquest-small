export function buildConstitutionQuizDeepDive({ stem, choice, legallyCorrect }: Input): string {
  const guide = GUIDES.find((item) => item.test.test(`${stem}\n${choice}`));
  const title = guide?.title || '憲法判例・条文の読み方';
  const rule = guide?.rule || '保障される権利や制度を特定し、制約の目的・必要性・手段の合理性、判断権者の裁量、判例の射程の順に確認します。条文と判例の結論を分け、学説上の説明を判例が明示した内容と混同しないことが重要です。';
  const verdict = legallyCorrect == null
    ? 'この肢は、並べ替え・複数選択の全体構造の中で判定します。'
    : legallyCorrect
      ? 'この肢の記述は、判例・条文の整理に沿っています。'
      : 'この肢の記述は、判例・条文の整理と一致しません。';
  const caseLike = /最高裁|判例|判決|訴訟|事件/.test(stem);
  const story = guide?.story || (caseLike
    ? `この問題では「${stem.replace(/\s+/g, ' ').slice(0, 120)}…」という紛争を通じ、具体的事実と憲法上の判断基準の結び付きが問われています。`
    : '');
  const keyword = choice.replace(/\s+/g, ' ').slice(0, 72);

  return [
    `# ${title}`,
    `## この肢の判定\n${verdict}`,
    story ? `## 判例のストーリー\n${story}` : '',
    `## 判断の軸\n${rule}`,
    '## ひっかけポイント\n「常に」「一切」「直ちに」「当然に」という断定が、例外・比較衡量・裁量の余地を消していないか確認します。',
    `## 30秒復習\nこの肢のキーワードは「${keyword}${choice.length > 72 ? '…' : ''}」。結論だけでなく、判断の軸のどこを言い換えた肢か確認しましょう。`,
  ].filter(Boolean).join('\n\n');
}
