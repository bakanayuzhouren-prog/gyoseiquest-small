function hayMatches(cluster: Cluster, hay: string): boolean {
  return cluster.trigger.test(hay || '');
}

export function appendShouhouConfusingTopicChunks(body: string, context: string): string {
  const hay = `${body || ''}\n${context || ''}`;
  let next = body || '';
  for (const cluster of CLUSTERS) {
    if (!hayMatches(cluster, hay)) continue;
    if (next.includes(cluster.marker)) continue;
    next = `${next.trim()}\n\n${cluster.chunk}`;
  }
  return next;
}

export function collectShouhouConfusingTopicChunks(haystack: string): string {
  const parts: string[] = [];
  for (const cluster of CLUSTERS) {
    if (!hayMatches(cluster, haystack || '')) continue;
    parts.push(cluster.chunk);
  }
  return parts.join('\n\n');
}

