const PROCEDURE_CONFUSION_CHUNK = `## 混同防止チャンク―似た手続保障を3つに分ける

### 1　第三者没収の「告知・弁解・防御」

刑事裁判で、**被告人ではない第三者の所有物を没収する場面**です。第三者は、そのままでは被告人の裁判に参加して自分の所有権を守れません。そこで財産を奪う前に、第三者本人へ没収されることを知らせ、言い分と証拠を出して争う機会を与える必要があります。

ここは原則として必要です。これを欠いて第三者の所有物を没収すると、憲法31条の適正手続によらず、憲法29条の財産権を侵害することになります。

### 2　行政処分と憲法31条の「告知・弁解・防御」

こちらは**行政庁が処分する場面の憲法上の最低ライン**です。行政手続は、刑事手続と違って目的・内容・緊急性が多様です。そのため最高裁は、行政処分なら常に必ず事前の告知・弁解・防御が必要だ、とはしていません。

必要性は、①制限される権利利益の内容・性質、②制限の程度、③処分により達成する公益の内容・程度・緊急性などを総合して判断します。

### 3　行政手続法の「聴聞」と「弁明の機会」

こちらは**憲法判例の抽象的基準ではなく、法律が定めた不利益処分の具体的手続**です。

| 場面 | 手続 | 覚え方 |
| --- | --- | --- |
| 許認可の取消しなど重い不利益処分 | 聴聞 | 口頭審理・質問・資料閲覧まで厚く保障 |
| それ以外の不利益処分 | 弁明の機会の付与 | 原則として書面で言い分を提出 |

ただし、緊急の必要がある場合や、資格喪失が裁判書などの客観的資料で直接証明される場合など、行政手続法13条2項の例外では省略できることがあります。

### 本番での見分け方

1. **「第三者の物を没収」**と出たら、第三者本人への告知・弁解・防御は必要。
2. **「行政処分にも憲法31条」**と出たら、「常に必ず」は誤り。総合衡量。
3. **「許可取消し・業務停止」**と出たら、行政手続法の聴聞か弁明かを判定。

合言葉は、**「第三者没収は参加させる、行政の憲法論はバランス、行手法は重さで振り分ける」**です。`;

export function appendConstitutionProcedureConfusionChunk(body: string, stem: string): string {
  if (!/適正手続|第三者没収|告知、弁解、防御/.test(stem)) return body;
  if (body.includes('混同防止チャンク―似た手続保障')) return body;
  return `${body.trim()}\n\n${PROCEDURE_CONFUSION_CHUNK}`;
}
