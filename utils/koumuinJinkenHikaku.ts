export function shouldAttachKoumuinJinkenCompare(aText: string, bText: string): boolean {
  const t = `${aText}\n${bText}`;
  if (t.includes(KOUMUIN_JINKEN_MARKER)) return false;
  const a = aText || '';
  if (/国民審査|レファレンダム|解職はリコール|選定し、罷免|国務大臣を任命|戸別訪問/.test(a)) {
    return false;
  }
  if (/訴訟事件/.test(a) && /懲戒/.test(a) && !/政治運動|政治的行為/.test(a)) {
    return false;
  }
  if (/岡口/.test(t) && !/政治的行為|猿払|堀越/.test(t)) return false;
  if (
    /猿払|堀越|宇治橋|君が代起立|起立斉唱命令|総合的に較量/.test(t)
  ) {
    return true;
  }
  if (/寺西判事|積極的に政治運動/.test(a) || (/積極的に政治運動/.test(t) && /裁判官/.test(a))) {
    return true;
  }
  if (/政治的行為/.test(t) && /政治的中立性/.test(t)) return true;
  if (/君が代/.test(t) && /懲戒|減給|慎重な考慮|職務命令/.test(t)) return true;
  if (/公務員/.test(t) && /人権制約|政治活動の禁止|政治的行為の禁止/.test(t)) return true;
  return false;
}
