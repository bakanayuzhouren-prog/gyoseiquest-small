const RELATED_PROCEDURE_QUESTIONS_CHUNK = `## 関連する憲法問題チャンク

この論点は、次の3か所を一組にして復習します。今回の第三者没収問題も、この組から外しません。

### 憲法18問・肢5―教科書検定と行政手続

行政処分に憲法31条の保障が及ぶ場合はありますが、**行政処分の相手方へ常に必ず告知・弁解・防御の機会が必要なわけではありません。** 行政手続は目的・内容・緊急性が多様だからです。

覚える結論：**行政手続の憲法論は、常に必要ではなく総合衡量。**

### 憲法24問・肢1―第三者没収と被告人の主張

第三者本人へ告知・弁解・防御の機会が必要である点は正しい一方、**被告人は違憲を主張できない**とする部分が誤りです。没収は被告人への付加刑であり、被告人も物の占有・使用収益を失い、第三者から賠償請求を受ける危険があるため、上告して争えます。

覚える結論：**第三者を手続に参加させる。被告人にも具体的利害がある。**

### 憲法25問―第三者没収の3段構造

今回の問題です。次の順で固定します。

1. 第三者本人に告知・弁解・防御の機会が必要。
2. 手続なしの没収は、適正手続によらない財産権侵害になる。
3. 被告人も付加刑と具体的利害を理由に違憲を主張できる。

### 3問を一行で区別

| 問題 | 主役 | 試験で問われる違い |
| --- | --- | --- |
| 憲法18問・肢5 | 行政処分の相手方 | 告知等は「常に必ず」ではない |
| 憲法24問・肢1 | 被告人 | 第三者の物でも違憲を主張できる |
| 憲法25問 | 第三者＋被告人 | 第三者の手続保障と被告人の主張適格をセットで問う |

本番では、**行政なら必要性を衡量、第三者没収なら第三者を参加、被告人にも争わせる**と唱えてから肢を読みます。`;

export function appendConstitutionProcedureRelatedQuestions(body: string, context: string): string {
  if (!/告知、弁解、防御|適正手続|第三者没収/.test(context)) return body;
  if (body.includes('関連する憲法問題チャンク')) return body;
  return `${body.trim()}\n\n${RELATED_PROCEDURE_QUESTIONS_CHUNK}`;
}
